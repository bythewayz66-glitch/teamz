// Builds src/data/library/seeds.generated.ts from Teamz's own fleet files.
// Prompts and first jobs are copied verbatim; nothing is written by hand.
// `node scripts/build-library-seeds.mjs` writes the file; `--check` exits 1 if it is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => JSON.parse(readFileSync(join(root, f), 'utf8'));

const runner = read('runner-agents.json');
const batch40 = read('new-agents-40.json');
const currency = read('new-agents-1-website-currency.json');
const futureWork = read('future-work-104.json');

// Where each template's agent definition and first job come from.
const PICKS = [
  { id: 'agent-orchestrator', from: ['runner-agents.json', runner], job: 'future-work', look: ['🧭', '#7c9cff'] },
  { id: 'agent-reviewer', from: ['runner-agents.json', runner], job: 'future-work', look: ['🛡️', '#5fd4a4'] },
  { id: 'agent-website-currency-agent', from: ['new-agents-1-website-currency.json', currency], job: 'firstJob', look: ['🌐', '#4fd1c5'] },
  { id: 'agent-drift-monitor', from: ['new-agents-40.json', batch40], job: 'firstJob', look: ['📡', '#f5c56b'] },
  { id: 'agent-backend-architect', from: ['runner-agents.json', runner], job: 'future-work', look: ['🏗️', '#a78bfa'] },
  { id: 'agent-code-reviewer', from: ['runner-agents.json', runner], job: 'future-work', look: ['🔍', '#60a5fa'] },
  { id: 'agent-qa-tester', from: ['runner-agents.json', runner], job: 'future-work', look: ['🧪', '#fb923c'] },
  { id: 'agent-bug-analysis-agent', from: ['runner-agents.json', runner], job: 'future-work', look: ['🐞', '#f87171'] },
];

const RUNNER_TOOLS = ['repo_read', 'stage_patch', 'fetch_url', 'room_read', 'web_search'];

const slug = (id) => id.replace(/^agent-/, '');

export function build() {
  const seeds = PICKS.map((p) => {
    const [file, list] = p.from;
    const a = list.find((x) => x.id === p.id);
    if (!a) throw new Error(`${p.id} not found in ${file}`);
    let firstJob = null;
    let firstJobFile = null;
    if (p.job === 'firstJob') {
      if (!a.firstJob) throw new Error(`${p.id} has no firstJob in ${file}`);
      firstJob = {
        title: a.firstJob.title,
        prompt: a.firstJob.prompt,
        kind: a.firstJob.type === 'cron' ? 'recurring' : 'one-off',
        schedule: a.firstJob.schedule ?? null,
      };
      firstJobFile = file;
    } else {
      const j = futureWork.find((x) => x.agentId === p.id);
      if (!j) throw new Error(`${p.id} has no job in future-work-104.json`);
      firstJob = { title: j.title, prompt: j.prompt, kind: 'one-off', schedule: null };
      firstJobFile = 'future-work-104.json';
    }
    return {
      id: `teamz.${slug(p.id)}`,
      name: a.name,
      emoji: p.look[0],
      accent: p.look[1],
      model: a.model,
      provider: a.provider ?? null,
      maxIterations: a.maxIterations ?? null,
      systemPrompt: a.systemPrompt,
      runnerTools: RUNNER_TOOLS.filter((t) => a.systemPrompt.includes(t)),
      firstJob,
      source: { kind: 'teamz-fleet', agentId: a.id, agentFile: file, firstJobFile },
    };
  });
  return seeds;
}

export function render(seeds) {
  return (
    '// GENERATED by scripts/build-library-seeds.mjs from the fleet files named in each\n' +
    '// seed\'s `source`. Do not edit by hand: run the script (`--check` to verify).\n' +
    "import type { LibrarySeed } from '../../lib/library';\n\n" +
    `export const LIBRARY_SEEDS: LibrarySeed[] = ${JSON.stringify(seeds, null, 2)};\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = join(root, 'src/data/library/seeds.generated.ts');
  const text = render(build());
  if (process.argv.includes('--check')) {
    const cur = readFileSync(out, 'utf8');
    if (cur !== text) {
      console.error('seeds.generated.ts is stale: run node scripts/build-library-seeds.mjs');
      process.exit(1);
    }
    console.log('seeds.generated.ts is up to date');
  } else {
    writeFileSync(out, text);
    console.log(`wrote ${out}`);
  }
}
